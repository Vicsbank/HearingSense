"""Writes the AudioSet → Hearing Sense kind table (taxonomy.py) as Swift source, so the app and
the benchmark use one mapping.

Usage: .venv/bin/python -I tools/experiments/model_benchmark/export_swift_taxonomy.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "audio_models"))
import candidates  # noqa: E402
import taxonomy  # noqa: E402

TARGET = taxonomy.ROOT / "packages/HearingSenseKit/Sources/SoundEventDetection/AudioSetLabelTable.swift"


def quoted(names):
    return ", ".join('"' + name.replace('"', '\\"') + '"' for name in names)


def main():
    labels = candidates.efficientat_labels()
    mapping, _ = taxonomy.audioset_label_to_kind(labels)
    lines = [
        "// Generated by tools/experiments/model_benchmark/export_swift_taxonomy.py from taxonomy.py.",
        "// Do not edit by hand: change taxonomy.py and run the script again.",
        "",
        "/// AudioSet class names (as YAMNet and EfficientAT report them) per Hearing Sense kind id.",
        "/// `exact`: Apple's classifier has a label for the same concept. `within`: the class lies",
        "/// inside the kind but Apple has no label of that name. AudioSet classes that are broader",
        "/// than a kind, or have no kind, are not listed and stay unmapped",
        "/// (docs/research/audioset_to_hearingsense_mapping.tsv lists all 527).",
        "enum AudioSetLabelTable {",
        "    static let byKind: [String: (exact: [String], within: [String])] = [",
    ]
    for kind in sorted({k for k, _ in mapping.values()}):
        exact = [name for name in labels if mapping.get(name) == (kind, "exact")]
        within = [name for name in labels if mapping.get(name) == (kind, "within")]
        lines.append(f'        "{kind}": (')
        lines.append(f"            exact: [{quoted(exact)}],")
        lines.append(f"            within: [{quoted(within)}]),")
    lines += ["    ]", "}", ""]
    TARGET.write_text("\n".join(lines))
    print("wrote", TARGET, "kinds", len({k for k, _ in mapping.values()}), "labels", len(mapping))


if __name__ == "__main__":
    main()
